package dev.aide.host.git

/**
 * Вытеснение старых снапшотов (T-1.19).
 *
 * Чистая функция: список ссылок и множество используемых — на входе, ссылки на удаление
 * — на выходе. О том, какие снапшоты в использовании, знает хост (задачи и их прогоны),
 * а не git, поэтому защита приходит сюда снаружи (`TaskSnapshotGuard`).
 */
internal object SnapshotPolicy {

    /**
     * Сколько последних снапшотов хранится.
     *
     * Число, а не срок: считать по времени значит зависеть от часов, а порядок ссылок
     * по числовой метке и так задан. Пятидесяти хватает, чтобы прогон с десятками шагов
     * был откатываем целиком, а глубже история шагов не нужна — она есть в коммитах.
     */
    const val KEEP_COUNT: Int = 50

    /**
     * Ссылки, которые нужно удалить, чтобы после добавления новой осталось [KEEP_COUNT].
     *
     * Вытесняются самые старые из тех, что не в использовании: если старейший снапшот
     * принадлежит незакрытой задаче, он остаётся, а уходит следующий за ним. Поэтому
     * хранимых ссылок может оказаться больше [KEEP_COUNT] — ровно на число используемых.
     *
     * @param refs все ссылки снапшотов в порядке создания, от старых к новым.
     * @param inUse ссылки, на которые ссылается незакрытая задача: их вытеснять нельзя.
     */
    fun evictable(refs: List<String>, inUse: Set<String>): List<String> {
        val overflow = refs.size - KEEP_COUNT
        if (overflow <= 0) return emptyList()
        return refs.filterNot { it in inUse }.take(overflow)
    }
}
