package dev.aide.host.git

import dev.aide.domain.FileChangeKind
import dev.aide.protocol.ProtocolError

/** Файл, изменённый относительно HEAD. */
data class ChangedFile(
    /** Путь относительно корня репозитория. */
    val path: String,
    /** Что произошло с файлом. */
    val changeKind: FileChangeKind,
    /** Прежний путь при переименовании; null в остальных случаях. */
    val previousPath: String? = null,
)

/** Коммит в истории. */
data class CommitInfo(
    /** Полный хеш коммита. */
    val hash: String,
    /** Короткий хеш для показа в UI. */
    val shortHash: String,
    /** Первая строка сообщения. */
    val message: String,
    /** Автор в формате «Имя <почта>». */
    val author: String,
    /** Время коммита в миллисекундах от эпохи. */
    val committedAtEpochMillis: Long,
)

/**
 * Чтение состояния git-репозитория и первая изменяющая операция — ветка задачи.
 *
 * Интерфейс отделён от реализации: JGit — не единственный возможный источник
 * (этап 6 добавляет Rust-модуль для git-операций через FFI, § 8.1), а задачи
 * этапа 1 работают с этим интерфейсом, а не с JGit напрямую.
 */
interface GitRepository : AutoCloseable {

    /** Имя текущей ветки; для репозитория без коммитов возвращает имя ещё не созданной ветки. */
    fun currentBranch(): String

    /** Короткий хеш HEAD; пустая строка, если коммитов нет. */
    fun headCommit(): String

    /** Изменения относительно HEAD: изменённые, добавленные, удалённые и переименованные файлы. */
    fun changedFiles(): List<ChangedFile>

    /** История коммитов текущей ветки, от нового к старому. */
    fun commitLog(limit: Int = DEFAULT_LOG_LIMIT): List<CommitInfo>

    /**
     * Обеспечивает ветку [branch] и переключает в неё рабочий каталог (T-1.18).
     *
     * Идемпотентно: ветки нет — создаётся от текущего HEAD; ветка есть — прогон
     * продолжает её. Ref, история и рабочее дерево при этом не перезаписываются:
     * откат и перезапись — не то, что делает повторный запуск задачи.
     *
     * Отказ возвращается результатом, а не исключением: «нет коммитов», «HEAD отсоединён»
     * и «репозиторий только для чтения» — состояния репозитория, которые обязан объяснить
     * движок, а не сбой чтения, ради которого существует [GitAccessException].
     */
    fun ensureTaskBranch(branch: String): TaskBranchOutcome

    /**
     * Коммитит изменения в ветке [branch] сообщением [message] (T-1.11).
     *
     * Автор — постоянная личность агента ([AGENT_AUTHOR_NAME], [AGENT_AUTHOR_EMAIL]),
     * а не `user.name`/`user.email`: этим выполняется инвариант 4 — коммит агента отличим
     * от коммита человека (§ 8.3). Ставится в индекс только то, что показывает `status`
     * ([changedFiles]), а не слепой `add -A`: тот не уважает `.gitignore`. Чистое дерево —
     * [StepCommitOutcome.NothingToCommit], а не пустой коммит.
     *
     * Отказ возвращается результатом, а не исключением: «не та ветка» и «git отказал» —
     * состояния репозитория, которые обязан объяснить движок, а не сбой чтения.
     */
    fun commitStep(branch: String, message: String): StepCommitOutcome

    /**
     * Ставит снапшот: ссылку [ref] на текущий HEAD (T-1.19).
     *
     * Рабочее дерево, HEAD и история при этом не трогаются: снапшот — ссылка на уже
     * существующий коммит, а не коммит и не копия дерева. У репозитория без коммитов
     * снапшота нет ([SnapshotOutcome.NoHead]), а сбой записи ссылки — отказ
     * ([SnapshotOutcome.Refused]), оба значением, а не исключением: движок обязан
     * получить код причины, а не оставить прогон с исключением в предохранителе воркера.
     */
    fun createSnapshot(ref: String): SnapshotOutcome

    /** Ссылки снапшотов в порядке создания, от старых к новым (T-1.19). */
    fun snapshotRefs(): List<String>

    /** Удаляет ссылки снапшотов; их коммиты остаются в истории — ссылка и история не одно и то же. */
    fun deleteSnapshots(refs: List<String>)

    /**
     * Отложенные правки пользователя (T-1.59).
     *
     * Отдельный объект, а не два метода здесь: операция двигает рабочее дерево и индекс
     * (в отличие от остальных), и у неё свои предпроверки. Свойство, а не методы, ещё и
     * потому, что интерфейс с ними перешёл бы порог числа функций, который проверяет линтер.
     */
    val workStash: StashRepository

    companion object {
        /** Сколько коммитов отдаётся по умолчанию: столько помещается в список без подгрузки. */
        const val DEFAULT_LOG_LIMIT: Int = 50
    }
}

/**
 * Отложенные правки: отдельная операция над рабочим деревом (T-1.59).
 *
 * Значениями, а не исключением: «откладывать нечего» и «возврат конфликтует» — состояния
 * репозитория, которые обязан объяснить движок. Ссылка отложенного лежит вне `refs/stash`:
 * стек stash пользователя эта операция не трогает, а ссылка принадлежит задаче.
 */
interface StashRepository {

    /**
     * Откладывает незакоммиченные правки в ссылку [ref] и очищает рабочее дерево.
     *
     * Целиком, включая новые файлы: после откладывания рабочий каталог обязан совпасть
     * с HEAD, иначе переключение в ветку задачи перенесло бы туда правки человека (§ 8.3).
     * Отсутствие правок ([StashOutcome.Nothing]) — не ошибка, сбой — [StashOutcome.Refused].
     */
    fun stashEdits(ref: String, message: String): StashOutcome

    /**
     * Возвращает правки [ref] в рабочее дерево, переключаясь на [branch] (null — не переключаться).
     *
     * Пустая ссылка и отказ git — [StashReturnOutcome.Refused]; конфликт с работой агента —
     * [StashReturnOutcome.Conflict], и тогда ссылка остаётся: отложенное не теряется.
     */
    fun returnStashEdits(ref: String, branch: String?): StashReturnOutcome
}

/**
 * Как репозиторий поставил снапшот (T-1.19).
 *
 * Значениями, а не исключением: «коммитов нет» и «ссылку не записать» — состояния
 * репозитория, которые обязан объяснить движок. Первое прогон не отменяет, второе —
 * отказ: без снапшота у прогона нет точки отката.
 */
sealed interface SnapshotOutcome {

    /** Ссылка поставлена на текущий HEAD. */
    data object Created : SnapshotOutcome

    /** Коммитов нет: ссылаться не на что, и это не ошибка прогона. */
    data object NoHead : SnapshotOutcome

    /** Ссылку записать не удалось: каталог недоступен, ссылка не открывается или исход записи — отказ. */
    data object Refused : SnapshotOutcome
}

/** Префикс ссылок снапшотов: пространство имён вне `refs/heads`, поэтому их нет в списке веток (T-1.19). */
const val SNAPSHOT_REF_PREFIX: String = "refs/ai/snap/"

/**
 * Префикс ссылок на отложенные правки пользователя (T-1.59).
 *
 * Своё пространство имён, а не `refs/stash`: отложенное принадлежит задаче, в метке виден
 * её идентификатор, а стек stash пользователя не трогается — он его набирал для себя.
 */
const val STASH_REF_PREFIX: String = "refs/ai/stash/"

/**
 * Как репозиторий отложил правки пользователя (T-1.59).
 *
 * Значениями, а не исключением: «откладывать нечего» — обычное состояние чистого дерева,
 * а «отложить нельзя» обязан объяснить движок. Ветка, на которой были правки, едет вместе
 * с результатом: возвращать их нужно туда же, а имена ветки у движка нет.
 */
sealed interface StashOutcome {

    /** Правки отложены в ссылку [ref]; [branch] — ветка, на которой они были (null — отсоединённый HEAD). */
    data class Stashed(val ref: String, val branch: String?) : StashOutcome

    /** Откладывать нечего: рабочее дерево чистое. */
    data object Nothing : StashOutcome

    /** Правки отложить не удалось: git отказал, коммитов нет. */
    data object Refused : StashOutcome
}

/**
 * Как репозиторий вернул отложенные правки (T-1.59).
 *
 * [Conflict] не смешивается с [Refused]: конфликт — это ожидаемый исход, при котором правки
 * сохранены и ждут разбора человеком, а отказ — сбой git. При обоих ссылка остаётся на месте.
 */
sealed interface StashReturnOutcome {

    /** Правки вернулись в рабочее дерево, ссылка убрана. */
    data object Returned : StashReturnOutcome

    /** Возврат конфликтует с тем, что сделал агент; ссылка сохранена. */
    data object Conflict : StashReturnOutcome

    /** Вернуть не удалось (git отказал, ссылки нет); ссылка, если была, сохранена. */
    data object Refused : StashReturnOutcome
}

/**
 * Имя ссылки снапшота: метка времени числом и метка повода (T-1.19).
 *
 * Метка времени — миллисекунды, а не ISO-8601: двоеточия в именах ссылок git запрещены,
 * а числовая метка ещё и сортируется как есть, то есть старые снапшоты идут первыми.
 */
fun snapshotRefName(epochMillis: Long, label: String): String = "$SNAPSHOT_REF_PREFIX$epochMillis-$label"

/** Ошибка доступа к репозиторию, несущая типизированную причину. */
class GitAccessException(val error: ProtocolError) : Exception(error.toString())

/**
 * Как репозиторий обеспечил ветку задачи (T-1.18).
 *
 * В терминах git, без кодов прогона: git-слой не знает ни о задачах, ни о прогонах,
 * а перевод причины в код отказа делает адаптер порта (`TaskBranchGuard`).
 */
sealed interface TaskBranchOutcome {

    /** Ветки не было: создана от [base]. */
    data class Created(val base: String) : TaskBranchOutcome

    /** Ветка уже была: переключились в неё, ref и история не тронуты. */
    data object Existing : TaskBranchOutcome

    /** Ветку задачи получить нельзя; [reason] объясняет, почему именно. */
    data class Refused(val reason: TaskBranchRefusal) : TaskBranchOutcome
}

/** Почему репозиторий не может дать ветку задачи. */
enum class TaskBranchRefusal {

    /** Коммитов нет: ветку не от чего ответвлять. */
    NO_COMMITS,

    /** HEAD отсоединён: базовой ветки не существует, а угадывать её нельзя. */
    DETACHED_HEAD,

    /** Репозиторий нельзя изменить: ссылку на ветку записать некуда. */
    READ_ONLY,

    /** Git отказал в создании ветки или в переключении: правки мешают либо ссылка не пишется. */
    GIT_FAILED,
}

/**
 * Личность агента в истории git (T-1.11).
 *
 * Задана константой, а не взята из `user.name`/`user.email`: инвариант 4 требует, чтобы
 * автора изменения было видно в истории, а настройки пользователя описывают человека,
 * за которого коммитил бы агент. Коммиты человека остаются за его собственной личностью,
 * и по автору эти два вида правок не смешиваются (§ 8.3).
 */
const val AGENT_AUTHOR_NAME: String = "aide-agent"

/** Почта автора-агента: продолжение [AGENT_AUTHOR_NAME], вместе они образуют личность в git. */
const val AGENT_AUTHOR_EMAIL: String = "agent@aide.local"

/**
 * Чем закончился коммит шага агента (T-1.11).
 *
 * В терминах git, без кодов прогона: git-слой не знает ни о задачах, ни о прогонах,
 * а перевод причины в код отказа делает адаптер порта (`StepCommitGuard`).
 */
sealed interface StepCommitOutcome {

    /** Коммит создан; [hash] — его полный хеш. */
    data class Committed(val hash: String) : StepCommitOutcome

    /** Изменений нет: пустой коммит не создаётся (NFR-SAFE-5). */
    data object NothingToCommit : StepCommitOutcome

    /** Коммит не создан; [reason] объясняет, почему именно. */
    data class Refused(val reason: StepCommitRefusal) : StepCommitOutcome
}

/** Почему репозиторий не создал коммит шага. */
enum class StepCommitRefusal {

    /**
     * Текущая ветка не та, в которую собирались коммитить.
     *
     * Защита от «коммит уехал не туда»: работу агента нельзя записать в чужую ветку,
     * даже если переключение произошло не нами.
     */
    WRONG_BRANCH,

    /** Git отказал: индекс не пишется, объект не создаётся, каталог недоступен. */
    GIT_FAILED,
}
