package dev.aide.host.secrets

import com.sun.jna.platform.win32.Crypt32Util

/**
 * Шифрование блоба ключей (T-1.58).
 *
 * Отдельный интерфейс, а не вызов DPAPI по месту, по двум причинам. Первая: платформенное
 * шифрование нельзя запустить в тестах на другой платформе, а логика хранения блоба —
 * можно, если шифр подставляется. Вторая: «ключ не лежит открытым текстом» становится
 * проверяемым свойством хранилища, а не обещанием.
 */
interface SecretCipher {

    /** Шифрует открытый текст. */
    fun encrypt(plain: ByteArray): ByteArray

    /** Расшифровывает блоб; на чужой учётной записи или битом файле бросает исключение. */
    fun decrypt(blob: ByteArray): ByteArray
}

/**
 * DPAPI: шифрование силами операционной системы, ключом учётной записи пользователя.
 *
 * Почему не самодельная криптография: защищённое хранилище — ровно та задача, где
 * собственная схема (пароль в коде, AES с ключом рядом с файлом) даёт видимость защиты —
 * ключ шифрования лежит там же, где шифротекст, и утекает вместе с репозиторием.
 * Почему не обёртка над PowerShell: вызов внешнего процесса требует запущенного и
 * разрешённого PowerShell, строку с секретом пришлось бы передавать через командную
 * строку (видна в списке процессов) или через временный файл (снова открытый текст),
 * а ошибка была бы видна только по коду возврата. JNA вызывает те же функции `crypt32`
 * напрямую, в процессе хоста, и передаёт данные буфером памяти.
 *
 * DPAPI работает только на Windows: на другой платформе ни класс хранилища, ни этот
 * шифр не создаются — выбор делает [SecretStoreFactory].
 */
class DpapiSecretCipher : SecretCipher {

    override fun encrypt(plain: ByteArray): ByteArray = Crypt32Util.cryptProtectData(plain)

    override fun decrypt(blob: ByteArray): ByteArray = Crypt32Util.cryptUnprotectData(blob)
}
