package dev.aide.host

import dev.aide.host.config.AgentConfigStore
import java.nio.file.Path

/**
 * Состояние хоста на диске: база метаданных и файл настроек моделей (T-1.56).
 *
 * Экземпляр ровно один на хост, и это не удобство, а условие корректности: хранилище
 * настроек держит замок записи, поэтому два экземпляра на одном пути означали бы два
 * независимых замка — то есть отсутствие защиты от одновременной записи. Поэтому оба
 * пути создаются вместе, здесь, а не по месту каждым потребителем.
 *
 * Файл настроек лежит рядом с базой: обе части состояния принадлежат одному хосту,
 * и разносить их по каталогам значило бы однажды разойтись — база от одного запуска,
 * настройки от другого.
 */
class HostStorage private constructor(
    /** Путь к базе метаданных; null — база приложения по умолчанию. */
    val databasePath: Path?,

    /** Хранилище настроек моделей — единственный экземпляр на этот хост. */
    val config: AgentConfigStore,
) {

    companion object {

        /** Создаёт состояние хоста: настройки моделей лягут рядом с базой. */
        fun of(databasePath: Path? = null): HostStorage =
            HostStorage(databasePath, AgentConfigStore(AgentConfigStore.defaultPath(databasePath)))
    }
}
