package dev.aide.host.workspace

import dev.aide.host.git.GitRepository
import dev.aide.protocol.WorkspaceId
import dev.aide.tools.limits.WorkspaceBoundary
import java.util.concurrent.ConcurrentHashMap

/**
 * Открытый воркспейс и всё, чем с ним работают.
 *
 * Один объект на воркспейс, а не поля по разным классам: дерево, файлы, git и граница
 * описывают одно и то же — открытый каталог, — и разъехавшись по владельцам, они
 * однажды оказались бы от разных воркспейсов.
 */
class OpenedWorkspace(
    /** Воркспейс: идентификатор и канонический корень. */
    val workspace: Workspace,

    /** Чтение файлов по запросу клиента. */
    val fileSystem: WorkspaceFileSystem,

    /** Дерево файлов для клиента. */
    val treeBuilder: FileTreeBuilder,

    /** Граница воркспейса: единственный санкционированный доступ инструментов к файлам (§ 10.1). */
    val boundary: WorkspaceBoundary,

    /** Открытый репозиторий воркспейса. */
    val git: GitRepository,
)

/**
 * Воркспейсы, открытые клиентом (T-1.7).
 *
 * До сих пор владельцем открытых воркспейсов был обработчик сообщений этапа 0, и это
 * было верно, пока читал диск только он. Инструменты агента читают диск без запроса
 * клиента — прогон идёт своей корутиной, — поэтому владелец нужен общий: обработчик
 * открывает воркспейс, движок берёт его отсюда.
 *
 * **Агент работает в последнем открытом воркспейсе.** Точнее было бы, чтобы задача
 * несла идентификатор воркспейса, но `PostTask` его не передаёт: протокол этапа 1
 * такого поля не имеет, а добавлять его — решение о модели данных, а не деталь этого
 * класса. Пока воркспейс у клиента один (обычный случай), разницы нет; при двух
 * открытых агент будет работать в том, который открыт последним. Ограничение
 * записано в отчёт по T-1.7 и закрывается вместе с выбором воркспейса для задачи.
 *
 * Воркспейс не открыт — это не «ошибка хоста»: инструменту нечего читать, и он
 * получает отказ границы ([WorkspaceToolContext]).
 */
class OpenWorkspaces {

    private val opened = ConcurrentHashMap<WorkspaceId, OpenedWorkspace>()

    /**
     * Последний открытый воркспейс.
     *
     * `@Volatile`, потому что читает его корутина прогона, а пишет сессия клиента:
     * без этого прогон мог бы увидеть частично опубликованное состояние.
     */
    @Volatile
    private var lastOpened: OpenedWorkspace? = null

    /** Ставит воркспейс открытым; он же становится текущим. */
    fun add(workspace: OpenedWorkspace) {
        opened[workspace.workspace.id] = workspace
        lastOpened = workspace
    }

    /** Воркспейс по идентификатору; null — он не открыт или уже закрыт. */
    fun find(id: WorkspaceId): OpenedWorkspace? = opened[id]

    /** Воркспейс, в котором работает агент: см. KDoc класса. */
    fun current(): OpenedWorkspace? = lastOpened

    /**
     * Закрывает всё открытое.
     *
     * Репозитории закрываются здесь, а не у вызывающего: они — часть открытого
     * воркспейса, и разделив закрытие, легко забыть половину. Ошибка закрытия одного
     * репозитория не мешает закрыть остальные.
     */
    fun close() {
        opened.values.forEach { runCatching { it.git.close() } }
        opened.clear()
        lastOpened = null
    }
}
