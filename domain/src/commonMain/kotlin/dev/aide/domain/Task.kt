package dev.aide.domain

import kotlinx.datetime.Instant
import kotlinx.serialization.Serializable

/** Постановка задачи пользователем: текст или расшифровка голоса (§ 4). */
@Serializable
data class Task(
    /** Идентификатор задачи. */
    val id: TaskId,
    /** Короткое название, которое видно на карточке пакета. */
    val title: String,
    /** Исходная постановка: текст или расшифровка голоса (FR-AGENT-20, FR-AGENT-21). */
    val prompt: String,
    /** Ветка задачи вида `ai/<task-id>` (§ 8.3). */
    val branch: String,
    /**
     * Базовая ветка задачи: та, от которой ответвилась [branch]; null, пока прогон не начинался.
     *
     * Записывается один раз — при первом запуске задачи, когда ветка задачи создаётся
     * (T-1.18). Вывести её потом нечем: к приёмке пакета (T-1.20) HEAD уже стоит на ветке
     * задачи, а основную ветку к тому времени могли подвинуть, и `merge-base` дал бы
     * не то, что нужно. Поле аддитивное: у задач, записанных до T-1.18, его нет.
     */
    val baseBranch: String? = null,
    /**
     * Ссылка на отложенные незакоммиченные правки пользователя; null, если откладывать нечего.
     *
     * Прогон начинается с чистого дерева: правки человека, бывшие в рабочем дереве, уезжают
     * в отдельную ссылку git и возвращаются после завершения прогона (T-1.59). Ссылка хранится
     * на задаче, а не только в репозитории: без неё после падения хоста нечем связать отложенное
     * с задачей и вернуть его (NFR-SAFE-2, § 8.3). Пока поле непусто, правки ждут возврата —
     * это и показывает интерфейс. Поле аддитивное: у задач, записанных до T-1.59, его нет.
     */
    val stashRef: String? = null,
    /**
     * Ветка, на которой отложены правки [stashRef]; null — правок нет либо был отсоединённый HEAD.
     *
     * Возвращать правки нужно на ту ветку, где они были: дерево человека не должно оказаться
     * в ветке агента. Имя ветки не вывести из задачи потом (базовая ветка — цель приёмки, а не
     * место правок), поэтому оно запоминается рядом со ссылкой.
     */
    val stashBranch: String? = null,
    /** Текущее состояние задачи. */
    val status: TaskStatus,
    /**
     * Код причины отказа; null, пока задача не провалилась.
     *
     * Причина лежит на задаче, а не только на прогоне: планирование может не состояться
     * до создания прогона (например, провайдер модели не настроен), и тогда рассказать
     * пользователю об отказе больше нечем. Код, а не текст: понятную строку строит UI
     * из ресурсов (NFR-13).
     */
    val failureReason: String? = null,
    /** Момент постановки задачи. */
    val createdAt: Instant,
    /** Прогоны агента по этой задаче, в порядке запуска. */
    val runIds: List<RunId> = emptyList(),
)
