package dev.aide.domain

import kotlinx.serialization.Serializable

/**
 * Запрос подтверждения вызова инструмента, который хост показывает пользователю (T-1.13).
 *
 * Несёт всё, что нужно клиенту, чтобы нарисовать диалог: имя инструмента, аргументы,
 * ось и признак изменения репозитория. Текст «что произойдёт» строит клиент из ресурсов
 * (NFR-13), а не берёт description для модели.
 */
@Serializable
data class ToolApprovalRequest(
    /** Идентификатор вызова: по нему клиент отвечает на конкретный запрос. */
    val callId: ToolCallId,
    /** Прогон, в рамках которого предлагается вызов. */
    val runId: RunId,
    /** Имя инструмента. */
    val tool: String,
    /** Аргументы вызова в сериализованном виде. */
    val arguments: String,
    /** Ось разрешения: чтение или запись (FR-TOOLS-8). */
    val kind: ToolKind,
    /** Меняет ли вызов файлы репозитория (T-1.8). */
    val changesRepository: Boolean,
)
