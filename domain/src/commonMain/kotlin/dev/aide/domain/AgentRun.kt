package dev.aide.domain

import kotlinx.datetime.Instant
import kotlinx.serialization.Serializable

/**
 * Стоимость в миллионных долях единицы тарификации провайдера.
 * Единица выбрана целочисленной, чтобы суммы совпадали с журналом до последней цифры (§ 5.9).
 */
@Serializable
data class Cost(
    /** Накопленная стоимость. При [known] = false равно нулю и не учитывается в итогах. */
    val amountMicros: Long = 0,
    /** false — цена хотя бы одного вызова неизвестна; итог с такой позицией помечается как неполный (FR-COST-5). */
    val known: Boolean = true,
)

/** Один шаг плана, показанного до первого изменяющего действия (FR-AGENT-7). */
@Serializable
data class PlanStep(
    /** Порядковый номер шага, начиная с 0. */
    val index: Int,
    /** Что агент собирается сделать, одной строкой. */
    val summary: String,
    /** Состояние шага. */
    val status: StepStatus,
)

/** Один прогон агента по задаче (§ 4). */
@Serializable
data class AgentRun(
    /** Идентификатор прогона. */
    val id: RunId,
    /** Задача, по которой идёт прогон. */
    val taskId: TaskId,
    /** Текущее состояние прогона. */
    val state: RunState,
    /** Режим автономности, зафиксированный на старте; переключение режима его не меняет (FR-AGENT-5). */
    val mode: AutonomyMode,
    /** План, показанный до первого изменяющего действия. */
    val plan: List<PlanStep> = emptyList(),
    /** Идентификаторы вызовов инструментов этого прогона, в порядке выполнения. */
    val toolCallIds: List<ToolCallId> = emptyList(),
    /**
     * Снапшоты, поставленные этим прогоном, в порядке создания (T-1.19).
     *
     * По ним видно, на что ссылается незакрытая задача: вытеснение старых снапшотов
     * обязано сохранить то, к чему пользователь ещё вернётся (откат T-1.6, чекпоинты
     * T-1.17). Список живёт на прогоне, а не только в git: связать ссылку с задачей
     * иначе нечем, а вытеснение работает поверх задач и их прогонов и переживает
     * перезапуск хоста. Поле аддитивное: у прогонов, записанных до T-1.19, оно пустое.
     */
    val snapshots: List<SnapshotRef> = emptyList(),
    /**
     * Последний разобранный отчёт тестов и линтера этого прогона (T-1.10).
     *
     * Едет клиенту тем же событием, что и смена состояния (`RunStateChanged`): отдельного
     * сообщения и таблицы не заводится, пока по проводу идут только падения и замечания.
     * Инструменты кладут отчёт в результат вызова, а пишет его единственный писатель
     * состояния прогона (О-8); поле аддитивное — у прогонов до T-1.10 его нет.
     */
    val testReport: TestReport? = null,
    /** Момент старта прогона. */
    val startedAt: Instant,
    /** Момент завершения; null, пока прогон идёт. */
    val finishedAt: Instant? = null,
    /** Длительность прогона в миллисекундах (FR-AGENT-10). */
    val elapsedMillis: Long = 0,
    /** Накопленная стоимость прогона (FR-AGENT-10). */
    val cost: Cost = Cost(),
    /**
     * Алиас модели, на которой шёл прогон (T-1.56).
     *
     * Записывается один раз на старте прогона: без него стоимость прогона нечем
     * объяснить, а результат — воспроизвести (FR-AGENT-10, FR-COST-2). У прогонов,
     * начатых до появления настройки моделей, поле пустое.
     */
    val modelAlias: String = "",
    /** Причина прерывания: падение хоста, стоп пользователя или отказ инструмента. */
    val interruptReason: String? = null,
)
