package dev.aide.tools

import java.nio.file.Path

/**
 * Что инструменту нужно от хоста: граница воркспейса и корень для обхода (О-3, T-1.7).
 *
 * Порт, а не готовая пара «корень и файловая система»: проверка «путь внутри корня»
 * одна на все инструменты, и повторять её каждым из них значило бы однажды забыть её
 * в следующем. Реализация живёт в `host-core` и опирается на
 * [dev.aide.tools.limits.WorkspaceBoundary] — инструменты ходят на диск только через
 * этот порт, и другого санкционированного доступа у них нет.
 */
interface ToolContext {

    /**
     * Путь внутри корня воркспейса или [dev.aide.tools.limits.HardLimitViolation].
     *
     * Исключение, а не результат: нарушение жёсткого предела — отказ, который обязан
     * стать `ToolOutcome.DENIED` у вызывающего, а не «ошибка инструмента»; перевод
     * делает одна точка вызова, чтобы три инструмента не решали это по-разному.
     */
    fun resolveInside(path: String): Path

    /**
     * Корень воркспейса: отсюда идёт обход дерева.
     *
     * Обойти можно только то, что видно от корня, и это тот же корень, с которым
     * сверяется [resolveInside]; каталог `.git` при обходе не читается (решение 5).
     */
    val root: Path
}
