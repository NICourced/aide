package dev.aide.tools

/**
 * Реестр инструментов (О-3): поиск по имени и порядок объявления.
 *
 * Порядок сохраняется: определения уезжают модели в том порядке, в котором их собрал
 * хост, и тест на запрос к модели сверяется с ним, а не с порядком хэш-таблицы.
 */
class ToolRegistry(tools: List<AgentTool>) {

    /** Инструменты в порядке объявления. */
    val tools: List<AgentTool> = tools.toList()

    private val byName: Map<String, AgentTool> = tools.associateBy { it.name }

    init {
        // Одинаковые имена — ошибка сборки, а не выбор последнего: модель зовёт
        // инструмент по имени, и два разных инструмента за одним именем сделали бы
        // вызов неоднозначным молча. Ловится на старте хоста, а не в прогоне.
        require(byName.size == tools.size) {
            "имена инструментов обязаны быть уникальны: ${tools.map { it.name }}"
        }
    }

    /** Инструмент по имени; null — такого инструмента модели не объявляли. */
    fun find(name: String): AgentTool? = byName[name]
}
