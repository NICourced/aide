package dev.aide.tools.ports

import dev.aide.domain.RunId
import dev.aide.domain.SnapshotRef

/**
 * Чем кончилась попытка взять точку отката перед изменяющим вызовом (T-1.8).
 *
 * Результат, а не «ссылка или исключение»: пустой репозиторий — обычное состояние,
 * в котором ссылаться не на что, и это обязан объяснить агент, а не предохранитель
 * воркера. Значения принадлежат `host-tools`, а git-природа ссылки уезжает в
 * [SnapshotRef] из домена: модуль инструментов о git не знает (О-1).
 */
sealed interface ChangeSnapshot {

    /** Точка отката есть: [ref] указывает на коммит перед изменением. */
    data class Taken(val ref: SnapshotRef) : ChangeSnapshot

    /** Коммитов нет: ссылаться не на что, а без точки отката изменять нельзя (NFR-SAFE-2). */
    data object NoHead : ChangeSnapshot

    /** Ссылку записать не удалось; [reason] — код причины из словаря хоста. */
    data class Failed(val reason: String) : ChangeSnapshot
}

/**
 * Точка отката перед изменением — то, что нужно точке вызова (T-1.8, NFR-SAFE-2).
 *
 * Порт объявлен в `host-tools`, а реализуется в `host-core`: поставить ссылку в git
 * значит знать, какой воркспейс открыт, а модуль инструментов о git и воркспейсах
 * не знает (О-1). Спрашивает порт именно точка вызова — единственное место, где
 * проходят все инструменты (О-3): гарантия «без точки отката не меняем» иначе
 * обходилась бы вызовом в обход неё.
 *
 * Повторный вопрос при неизменном HEAD не создаёт вторую ссылку: это забота
 * реализации (решение 4), а не вызывающего — точка вызова не знает и не должна
 * знать, что такое HEAD. Прогон — часть вопроса: кэш ссылок принадлежит одному
 * прогону и не переезжает в следующий (О-8: прогон за раз один).
 */
fun interface ChangeSnapshots {

    /**
     * Возвращает точку отката для прогона [runId], ставя её при необходимости.
     *
     * [RunId] нужен, чтобы кэш «HEAD → ссылка» не пережил границу прогона: без него
     * следующий прогон у того же коммита получил бы ссылку предыдущего. Вызовы идут
     * из одной корутины прогона (О-8), поэтому реализации не обязаны быть
     * потокобезопасными — но и не должны бросать: сбой git переводится
     * в [ChangeSnapshot.Failed], иначе исключение ушло бы мимо точки вызова.
     */
    suspend fun beforeChange(runId: RunId): ChangeSnapshot
}
