package dev.aide.tools.ports

import dev.aide.domain.ToolCall

/**
 * Порт журнала вызовов (О-1, T-1.7): реализация живёт в `host-core` поверх хранилища.
 *
 * Порт, а не прямая запись в базу: `host-tools` не знает ни про SQLite, ни про схему
 * хоста — ему запрещено и то, и другое правилом границ модуля. Полноценный журнал
 * с фильтрами и страницами — T-1.3; здесь достаточно того, что вызов и его исход
 * не теряются.
 */
fun interface ToolCallRecorder {

    /**
     * Записывает вызов инструмента с исходом и длительностью.
     *
     * Вызывается ровно один раз на вызов, в том числе когда вызов отклонён правами
     * или границей воркспейса, — иначе отказ агента не оставлял бы следа.
     */
    fun record(call: ToolCall)
}
