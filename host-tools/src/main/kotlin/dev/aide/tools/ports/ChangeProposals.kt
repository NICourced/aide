package dev.aide.tools.ports

import dev.aide.domain.ChangeProposal

/**
 * Постоянная очередь неприменённых файловых предложений (T-1.15).
 *
 * Порт объявлен в `host-tools`, а реализация — в `host-core` поверх SQLite (О-1).
 * Сохранённые предложения используются при сборке пакета ревью (T-1.24); здесь
 * очередь только принимает и отдаёт записи, не удаляя их из приложения.
 */
fun interface ChangeProposals {

    /** Сохраняет предложение; повторный тот же идентификатор — ошибка вызывающего. */
    fun save(proposal: ChangeProposal)
}
