package dev.aide.tools.ports

/**
 * Чем кончилась попытка зафиксировать шаг агента (T-1.11).
 *
 * Результат, а не «хеш или исключение»: «коммитить нечего» — обычное состояние чистого
 * дерева, а «git отказал» обязан объяснить вызывающий, а не предохранитель воркера.
 * Значения принадлежат `host-tools`, а git-природа коммита наружу не протекает: модуль
 * инструментов о git не знает (О-1).
 */
sealed interface StepCommit {

    /** Коммит создан; [hash] — его полный хеш. */
    data class Committed(val hash: String) : StepCommit

    /** Изменений нет: пустой коммит не создаётся (NFR-SAFE-5). */
    data object NothingToCommit : StepCommit

    /** Шаг не зафиксирован; [reason] — код причины из словаря хоста. */
    data class Refused(val reason: String) : StepCommit
}

/**
 * Фиксация шага агента — то, что нужно внутреннему инструменту `commit_step` (T-1.11).
 *
 * Порт объявлен в `host-tools`, а реализуется в `host-core`: закоммитить значит знать,
 * какой воркспейс открыт, а модуль инструментов о git и воркспейсах не знает (О-1).
 * Ветка приходит аргументом, потому что её знает движок прогона, а не инструмент:
 * реализация сверяет её с текущей веткой и отказывает, если коммит уехал бы не туда.
 */
fun interface StepCommits {

    /**
     * Коммитит изменения ветки [branch] сообщением [message].
     *
     * Автора задаёт реализация: коммит шага обязан быть отличим от коммита человека
     * (инвариант 4, § 8.3). Вызовы идут из одной корутины прогона (О-8), поэтому
     * реализации не обязаны быть потокобезопасными — но и не должны бросать:
     * сбой git переводится в [StepCommit.Refused].
     */
    suspend fun commit(branch: String, message: String): StepCommit
}
