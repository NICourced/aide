package dev.aide.tools.sandbox

import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonObject

/**
 * Общее для инструментов `run_tests` и `run_lint` (T-1.10, решение 1).
 *
 * Схема аргументов, предел времени и текст отказа обязаны совпадать у обоих: их
 * различие — расхождение, которое заметили бы только по разнице в поведении двух
 * похожих инструментов. Поэтому общие значения лежат рядом, а не дублируются в
 * каждой из двух обёрток.
 */

/**
 * Схема аргументов тестов и линтера — пустой объект: аргументов у инструментов нет.
 *
 * Это не недосмотр: команду выбирает хост по маркерам проекта (решение 1), и модель
 * не может подсунуть свою под видом «тестов». Пустая схема честно говорит ей то же
 * самое — у вызова нет ни одного аргумента, и придумывать его не надо.
 */
internal val REPORT_ARGUMENTS_SCHEMA: JsonObject = buildJsonObject {
    put("type", "object")
    putJsonObject("properties") {}
}

/**
 * Предел времени тестов и линтера.
 *
 * Больше предела команды (две минуты у `run_command`): полный прогон тестов проекта
 * законно идёт дольше любой отдельной команды, и обрывать его на середине значило бы
 * объявлять таймаутом нормальную работу. Десять минут остаются границей, за которой
 * прогон почти наверняка завис, а не считает; исход `TIMEOUT` при этом формирует
 * инвокер, а [CommandRunner] убивает дерево процессов.
 */
internal const val REPORT_TOOL_TIMEOUT_MILLIS: Long = 600_000

/**
 * Отказ, когда проект не распознан по маркерам (решение 1).
 *
 * Явный отказ с подсказкой, а не догадка: «запустить наугад» могло бы выполнить
 * не то, что просили. Модель, прочитав это, поправится сама — `run_command` у неё есть.
 */
internal const val UNRECOGNIZED_PROJECT: String =
    "не знаю, как запускать это в проекте: в корне не найдено ни Gradle, ни Maven. " +
        "Запустите нужную команду инструментом run_command"
