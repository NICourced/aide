package dev.aide.tools

import dev.aide.domain.Cost
import dev.aide.domain.ToolOutcome
import dev.aide.domain.ToolPermission
import dev.aide.tools.permission.ToolKind
import kotlinx.serialization.json.JsonObject

/**
 * Сколько инструмент вправе работать, если он не объявил своё.
 *
 * Число с причиной: инструмент — это ввод-вывод (чтение файла, обход дерева), и
 * зависший вызов останавливает весь прогон, а не один шаг. Полминуты хватает
 * на большой файл и на файловую систему под нагрузкой; ждать дольше значило бы
 * прятать от пользователя зависание, а не лечить его.
 */
const val DEFAULT_TOOL_TIMEOUT_MILLIS: Long = 30_000

/**
 * Инструмент агента (О-3): один тип на всё, что модель вправе вызвать.
 *
 * Так устроены и реестр, и права, и журнал: имя и схема аргументов уходят модели,
 * [kind] решает, какую из двух осей разрешения спрашивать (FR-TOOLS-8), а [execute]
 * выполняет работу. Инструмент не знает ни про базу, ни про протокол, ни про движок
 * прогона — он знает [ToolContext] и возвращает [ToolResult].
 */
interface AgentTool {

    /** Имя, под которым инструмент видит модель. */
    val name: String

    /** Описание для модели: по нему она и решает, когда инструмент звать. */
    val description: String

    /** JSON-схема аргументов: уходит модели и по ней же проверяются аргументы до вызова. */
    val argumentsSchema: JsonObject

    /** Ось прав: чтение или запись (FR-TOOLS-8). */
    val kind: ToolKind

    /**
     * Объявленное умолчание инструмента (О-4).
     *
     * Встроенное чтение объявляет `read = ALLOW`: запрещать чтение внутри воркспейса
     * по умолчанию нельзя — агент не заработает вовсе, а пользователь получит диалог
     * подтверждения на каждый прочитанный файл. Запись и исполнение объявляют `ASK`.
     */
    val declaredPermission: ToolPermission

    /** Предел времени вызова; превышение даёт `ToolOutcome.TIMEOUT`, а не зависший прогон. */
    val timeoutMillis: Long get() = DEFAULT_TOOL_TIMEOUT_MILLIS

    /**
     * Выполняет вызов; ошибка возвращается в [ToolResult], а не бросается наружу.
     *
     * Единственное исключение — [dev.aide.tools.limits.HardLimitViolation]: выход за
     * воркспейс не «ошибка инструмента», а отказ жёсткого предела, и в `DENIED` его
     * переводит точка вызова, а не каждый инструмент по-своему.
     */
    suspend fun execute(arguments: JsonObject, context: ToolContext): ToolResult
}

/**
 * Результат, который уходит обратно в диалог с моделью.
 *
 * Текст, а не структура: модель читает текст, и то, что увидит пользователь, — тоже
 * он. [cost] у инструментов этапа 1 нулевая (у чтения платить не за что), но поле есть
 * с самого начала: иначе стоимость вызова пришлось бы добавлять в четыре типа сразу.
 */
data class ToolResult(
    /** Текст для модели: либо содержимое, либо объяснение отказа. */
    val text: String,
    /** Чем закончился вызов; от этого зависит цвет в журнале и реакция движка. */
    val outcome: ToolOutcome,
    /** Стоимость вызова; у чтения нулевая. */
    val cost: Cost = Cost(),
)

/** Успешный результат: инструмент сделал то, о чём просили. */
fun toolSuccess(text: String): ToolResult = ToolResult(text = text, outcome = ToolOutcome.SUCCESS)

/**
 * Отказ инструмента: модель должна понять, что пошло не так, и поправиться.
 *
 * `FAILURE`, а не `DENIED`: DENIED означает «запрещено» — настройкой прав или границей
 * воркспейса, и путать запрет с неудачей значило бы врать в журнале.
 */
fun toolFailure(text: String): ToolResult = ToolResult(text = text, outcome = ToolOutcome.FAILURE)

