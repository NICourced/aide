package dev.aide.tools

import dev.aide.domain.Cost
import dev.aide.domain.SnapshotRef
import dev.aide.domain.TestReport
import dev.aide.domain.ToolOutcome
import dev.aide.domain.ToolPermission
import dev.aide.tools.permission.ToolKind
import kotlinx.serialization.json.JsonObject

/**
 * Сколько инструмент вправе работать, если он не объявил своё.
 *
 * Число с причиной: инструмент — это ввод-вывод (чтение файла, обход дерева), и
 * зависший вызов останавливает весь прогон, а не один шаг. Полминуты хватает
 * на большой файл и на файловую систему под нагрузкой; ждать дольше значило бы
 * прятать от пользователя зависание, а не лечить его.
 */
const val DEFAULT_TOOL_TIMEOUT_MILLIS: Long = 30_000

/**
 * Кому адресован инструмент: модели или только движку прогона (T-1.11, О-3).
 *
 * Умолчание — [MODEL]: инструмент заводится ровно затем, чтобы его звала модель.
 * [INTERNAL] нужен `commit_step`: движок вызывает его сам после изменяющего шага,
 * а решение «когда фиксировать» модели не отдаётся (§ 8.3).
 */
enum class ToolVisibility { MODEL, INTERNAL }

/**
 * Инструмент агента (О-3): один тип на всё, что зовёт агент — модель или движок прогона.
 *
 * Так устроены и реестр, и права, и журнал: имя и схема аргументов уходят модели,
 * [kind] решает, какую из двух осей разрешения спрашивать (FR-TOOLS-8), а [execute]
 * выполняет работу. Инструмент не знает ни про базу, ни про протокол, ни про движок
 * прогона — он знает [ToolContext] и возвращает [ToolResult].
 *
 * Зовёт инструменты не только модель: [visibility] = [ToolVisibility.INTERNAL] заводится
 * для тех, что вызывает движок (T-1.11, `commit_step`), и модель их не видит. Поэтому тип
 * описывает обе стороны — и то, что уезжает модели определением, и то, что хост исполняет сам.
 */
interface AgentTool {

    /** Имя, под которым инструмент видит модель. */
    val name: String

    /** Описание для модели: по нему она и решает, когда инструмент звать. */
    val description: String

    /** JSON-схема аргументов: уходит модели и по ней же проверяются аргументы до вызова. */
    val argumentsSchema: JsonObject

    /** Ось прав: чтение или запись (FR-TOOLS-8). */
    val kind: ToolKind

    /**
     * Меняет ли вызов файлы репозитория (T-1.10).
     *
     * По умолчанию — «да, если инструмент пишущий»: этого достаточно для записи файла
     * и терминала, где опасность и ось прав совпадают. Тесты и линтер объявляют
     * `false` явно: они исполняются (ось прав — запись, О-4/NG7), но репозиторий не
     * меняют — команда `test` пишет отчёт в `build/`, а это артефакт, не результат
     * работы агента. Иначе прогон тестов порождал бы коммит шага и мог закоммитить
     * артефакты сборки от имени агента, если `build/` не в `.gitignore`. По этому
     * признаку движок решает, коммитить ли шаг, а точка вызова — ставить ли точку
     * отката: незачем охранять то, что не меняется.
     */
    val changesRepository: Boolean get() = kind == ToolKind.WRITE

    /**
     * Порождает ли вызов отчёт тестов или линтера (T-1.10).
     *
     * По этому признаку точка вызова отмечает исход «не уложился в лимит» в отчёте:
     * без него `TestState.TIMEOUT` недостижим — инструмент на таймауте не успевает
     * вернуть ничего, а `RunStateWriter` пишет отчёт только из результата. `true`
     * у `run_tests` и `run_lint`; у остальных инструментов отчёта нет, и выдумывать
     * его на таймауте не нужно.
     */
    val producesTestReport: Boolean get() = false

    /**
     * Виден ли инструмент модели (T-1.11).
     *
     * В определения реестра для модели попадают только [ToolVisibility.MODEL]: внутренний
     * инструмент вызывается движком, и показывать его модели значило бы дать ей право
     * решать, когда фиксировать шаг. Вызов при этом всё равно идёт через точку вызова —
     * ради журнала и замера времени (О-3).
     */
    val visibility: ToolVisibility get() = ToolVisibility.MODEL

    /**
     * Объявленное умолчание инструмента (О-4).
     *
     * Встроенное чтение объявляет `read = ALLOW`: запрещать чтение внутри воркспейса
     * по умолчанию нельзя — агент не заработает вовсе, а пользователь получит диалог
     * подтверждения на каждый прочитанный файл. Запись и исполнение объявляют `ASK`.
     */
    val declaredPermission: ToolPermission

    /** Предел времени вызова; превышение даёт `ToolOutcome.TIMEOUT`, а не зависший прогон. */
    val timeoutMillis: Long get() = DEFAULT_TOOL_TIMEOUT_MILLIS

    /**
     * Выполняет вызов; ошибка возвращается в [ToolResult], а не бросается наружу.
     *
     * Единственное исключение — [dev.aide.tools.limits.HardLimitViolation]: выход за
     * воркспейс не «ошибка инструмента», а отказ жёсткого предела, и в `DENIED` его
     * переводит точка вызова, а не каждый инструмент по-своему.
     */
    suspend fun execute(arguments: JsonObject, context: ToolContext): ToolResult
}

/**
 * Результат, который уходит обратно в диалог с моделью.
 *
 * Текст, а не структура: модель читает текст, и то, что увидит пользователь, — тоже
 * он. [cost] у инструментов этапа 1 нулевая (у чтения платить не за что), но поле есть
 * с самого начала: иначе стоимость вызова пришлось бы добавлять в четыре типа сразу.
 */
data class ToolResult(
    /** Текст для модели: либо содержимое, либо объяснение отказа. */
    val text: String,
    /** Чем закончился вызов; от этого зависит цвет в журнале и реакция движка. */
    val outcome: ToolOutcome,
    /** Стоимость вызова; у чтения нулевая. */
    val cost: Cost = Cost(),
    /**
     * Точка отката, поставленная перед изменяющим вызовом (T-1.8).
     *
     * Ненулевая у любого **выполненного** изменяющего вызова — и успешного, и неуспешного
     * по внутренней причине: снапшот ставится до выполнения и обязан попасть в
     * `AgentRun.snapshots`, иначе вытеснение сочло бы его брошенным. Единственный
     * потребитель ссылки — движок прогона; инструмент её пользователю не показывает.
     * У читающих вызовов здесь null: читать точку отката незачем.
     */
    val snapshotRef: SnapshotRef? = null,
    /**
     * Отчёт тестов или линтера, если вызов их запускал (T-1.10).
     *
     * Инструмент не знает `runId` и потому не пишет в прогон сам: отчёт едет результатом,
     * а вкладывает его в прогон движок — единственный писатель состояния (О-8). У вызовов,
     * которые ничего не запускали, здесь null.
     */
    val testReport: TestReport? = null,
)

/** Успешный результат: инструмент сделал то, о чём просили. */
fun toolSuccess(text: String, testReport: TestReport? = null): ToolResult =
    ToolResult(text = text, outcome = ToolOutcome.SUCCESS, testReport = testReport)

/**
 * Отказ инструмента: модель должна понять, что пошло не так, и поправиться.
 *
 * `FAILURE`, а не `DENIED`: DENIED означает «запрещено» — настройкой прав или границей
 * воркспейса, и путать запрет с неудачей значило бы врать в журнале.
 */
fun toolFailure(text: String, testReport: TestReport? = null): ToolResult =
    ToolResult(text = text, outcome = ToolOutcome.FAILURE, testReport = testReport)

