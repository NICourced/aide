package dev.aide.agent.provider

import dev.aide.agent.llm.LlmClient
import dev.aide.domain.ModelCheckFailure

/**
 * Модель, выбранная для прогона (T-1.56).
 *
 * Клиент отдаётся вместе с алиасом: движок берёт модель **один раз на старте прогона**,
 * записывает алиас в `AgentRun.modelAlias`, а сам клиент использует до конца прогона.
 * Поэтому смена модели в настройках не меняет правила идущего прогона (FR-AGENT-5):
 * он уже держит выбранный транспорт, а не спрашивает настройки на каждом шаге.
 */
data class ConfiguredModel(
    /** Алиас модели, под которым она записана в прогон. */
    val alias: String,
    /** Клиент выбранной модели. */
    val client: LlmClient,
)

/**
 * Источник модели для прогона.
 *
 * Отказ — не исключение, а `Result`: провайдер может быть не настроен, переменной
 * окружения с ключом может не быть, алиас может не существовать, и всё это —
 * обычные состояния, а не сбой хоста. Код отказа попадает в причину задачи,
 * а имя отсутствующей переменной — на экран проверки модели (NFR-13).
 */
fun interface ModelProvider {

    /** Текущая модель или типизированный отказ. */
    fun current(): Result<ConfiguredModel>
}

/**
 * Всё, что хост знает о моделях: выбор модели для прогона и проверка доступа из настроек.
 *
 * Движок зависит только от [ModelProvider] — проверку он не делает вовсе. Один тип на две
 * роли потому, что это одно и то же знание о моделях: развести их на два независимых
 * источника значило бы допустить их расхождение (например, проверять одну модель, а
 * запускать другую).
 *
 * Оба метода обязательны: умолчание «проверка не поддержана» жило бы в main-коде ради
 * тестов, а источник, который проверять не умеет, обязан сказать это сам — явно и видимо
 * в своём коде, а не унаследовать молча.
 */
interface AgentModels : ModelProvider {

    /** Текущая модель для прогона или типизированный отказ. */
    override fun current(): Result<ConfiguredModel>

    /** Проверяет доступ к модели: null — доступ подтверждён. */
    suspend fun check(alias: String): ModelCheckFailure?
}

/**
 * Отказ выбрать модель, несущий типизированную причину.
 *
 * Отдельный тип, а не `Result.failure(IllegalStateException)`: движку нужно **различить**
 * «модель не настроена» и «поломка чтения конфигурации», потому что первое — нормальное
 * состояние чистой установки, а второе — дефект, о котором надо писать в журнал.
 */
class ModelUnavailableException(val failure: ModelCheckFailure) : Exception(failure.toString())
