package dev.aide.agent.ports

import dev.aide.domain.TaskId

/**
 * Куда делись незакоммиченные правки пользователя (T-1.59).
 *
 * Откладывание целиком, включая новые файлы: незакоммиченный новый файл — такая же правка
 * человека, и оставить его в дереве значит показать агенту то, чего в ветке задачи нет.
 * Результат, а не исключение: пустое дерево — обычное состояние (откладывать нечего),
 * а «откладывать нельзя» обязан объяснить движок кодом причины (NFR-13).
 */
sealed interface TaskStash {

    /**
     * Правки отложены: [ref] — ссылка на них, [branch] — ветка, на которой они были.
     *
     * [branch] = null означает отсоединённый HEAD: возвращать правки нужно туда же, но имени
     * ветки у этого состояния нет, а выдумывать его нельзя.
     */
    data class Stashed(val ref: String, val branch: String?) : TaskStash

    /** Откладывать нечего: рабочее дерево чистое. */
    data object Nothing : TaskStash

    /** Правки отложить нельзя; [reason] — код причины отказа прогона. */
    data class Refused(val reason: String) : TaskStash
}

/**
 * Чем закончился возврат отложенных правок (T-1.59).
 *
 * [Conflict] и [Refused] — не «правки пропали»: отложенное остаётся ссылкой в репозитории
 * и ждёт разбора человеком. Никакого drop при неудаче: тихая потеря правок дороже
 * неудобства явного конфликта (§ 8.3).
 */
sealed interface StashReturn {

    /** Правки вернулись в рабочее дерево, ссылка на них убрана. */
    data object Returned : StashReturn

    /** Возврат конфликтует с тем, что сделал агент; [reason] — код причины. */
    data class Conflict(val reason: String) : StashReturn

    /** Правки вернуть не удалось (git отказал, воркспейс закрыт); [reason] — код причины. */
    data class Refused(val reason: String) : StashReturn
}

/**
 * Единственное, что движку нужно от отложенных правок (T-1.59, О-1).
 *
 * Рантайм агента о git не знает: ссылки, рабочее дерево и конфликты — дело хоста, а движок
 * получает узкий порт «отложи правки перед прогоном и верни их после». Имя ссылки собирает
 * реализация: движку оно не нужно, а хранится результат на задаче.
 */
interface WorkStash {

    /** Откладывает правки задачи [taskId] в сторону; исход — [TaskStash]. */
    suspend fun stash(taskId: TaskId): TaskStash

    /**
     * Возвращает отложенные правки [ref] на ветку [branch] (null — не переключаться).
     *
     * Идемпотентным это не сделано намеренно: повторный возврат той же ссылки после успеха
     * невозможен — успешный возврат убирает ссылку, и повтор даёт [StashReturn.Refused].
     */
    suspend fun restore(ref: String, branch: String?): StashReturn
}
