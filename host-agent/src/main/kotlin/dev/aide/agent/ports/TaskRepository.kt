package dev.aide.agent.ports

import dev.aide.domain.Task
import dev.aide.domain.TaskId

/** Задачи и очередь на выполнение (T-1.1). Реализация — в `host-core` над хранилищем. */
interface TaskRepository {

    /** Сохраняет задачу; повторная запись с тем же `id` заменяет прежнюю. */
    fun save(task: Task)

    /** Читает задачу по идентификатору; неизвестный идентификатор даёт null. */
    fun load(id: TaskId): Task?

    /**
     * Задачи, работа по которым ещё не завершена, в порядке постановки.
     *
     * Порядок задаёт хранилище, а не вызывающий: очередь — FIFO по времени
     * постановки, и восстанавливать этот порядок в нескольких местах не нужно (О-8).
     */
    fun unfinished(): List<Task>
}
