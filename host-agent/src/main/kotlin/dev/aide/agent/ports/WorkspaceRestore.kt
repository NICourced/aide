package dev.aide.agent.ports

import dev.aide.domain.SnapshotRef

/**
 * Чем закончилось восстановление рабочего дерева к снапшоту (T-1.4).
 *
 * Результат, а не «дерево или исключение»: «восстанавливать нечего» и «git отказал» —
 * обычные состояния репозитория, которые обязан объяснить движок, а не сбой хоста.
 * Код отказа лежит в [Refused.reason] — из словаря [dev.aide.agent.RunInterruptReason]:
 * понятную строку строит UI (NFR-13).
 */
sealed interface WorkspaceRestoreOutcome {

    /** Дерево приведено к снапшоту: отслеживаемые правки откачены, лишние файлы убраны. */
    data object Restored : WorkspaceRestoreOutcome

    /** Восстанавливать нечего: у прогона снапшота нет (пустой репозиторий). */
    data object Nothing : WorkspaceRestoreOutcome

    /** Восстановить не удалось; [reason] — код причины отказа прогона. */
    data class Refused(val reason: String) : WorkspaceRestoreOutcome
}

/**
 * Единственное, что движку нужно от восстановления дерева (T-1.4, О-1).
 *
 * Рантайм агента о git не знает: ревизии, рабочее дерево и очистка — дело хоста, а движок
 * получает узкий порт «верни дерево к последнему снапшоту прогона». Снапшот передаётся
 * ссылкой, а не именем задачи: какие снапшоты в использовании, знает хост, а какой
 * из них последний — прогон, и угадывать это в адаптере значило бы повторять порядок,
 * который движок уже знает.
 */
fun interface WorkspaceRestore {

    /**
     * Приводит рабочее дерево к снапшоту [snapshot].
     *
     * [snapshot] = null означает «у прогона снапшота нет» (пустой репозиторий) —
     * восстанавливать нечего, и это [WorkspaceRestoreOutcome.Nothing], а не отказ:
     * останавливать прогон из-за этого нельзя.
     */
    suspend fun restoreTo(snapshot: SnapshotRef?): WorkspaceRestoreOutcome
}
