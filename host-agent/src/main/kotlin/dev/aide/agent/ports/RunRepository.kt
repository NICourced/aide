package dev.aide.agent.ports

import dev.aide.domain.AgentRun
import dev.aide.domain.RunId

/**
 * Сохранение прогонов (T-1.1).
 *
 * Порт узкий, по одной сущности: реализация живёт в `host-core` поверх хранилища,
 * потому что единственное место, где хост держит базу, — это `host-core` (О-1).
 * Рантайм агента о базе не знает.
 */
interface RunRepository {

    /** Сохраняет прогон; повторная запись с тем же `id` заменяет прежнюю. */
    fun save(run: AgentRun)

    /** Читает прогон по идентификатору; неизвестный идентификатор даёт null. */
    fun load(id: RunId): AgentRun?

    /**
     * Прогоны, не завершившиеся до остановки хоста (`finishedAt` = null).
     *
     * По ним восстановление после падения помечает прогон прерванным, а не
     * продолжает его с середины молча (T-1.1).
     */
    fun unfinished(): List<AgentRun>
}
