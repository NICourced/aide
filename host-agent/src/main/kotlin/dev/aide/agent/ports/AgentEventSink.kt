package dev.aide.agent.ports

import dev.aide.domain.AgentRun
import dev.aide.domain.Task

/**
 * Куда движок отдаёт изменения состояния прогонов и статусов задач (T-1.1).
 *
 * Хост рассылает их клиентам как события без запроса (§ 8.4); рантайм агента
 * о транспорте не знает. Событие уходит **после** записи в базу — этот порядок
 * проверяется тестом (О-8), и он одинаков для прогона и для задачи.
 */
interface AgentEventSink {

    /** Сообщает о прогоне в новом состоянии. */
    suspend fun runStateChanged(run: AgentRun)

    /**
     * Сообщает о задаче в новом статусе.
     *
     * Отдельный метод, а не «ещё одно событие прогона»: задача меняет статус и до
     * появления прогона — при постановке в очередь и при отказе планирования.
     */
    suspend fun taskStateChanged(task: Task)
}
