package dev.aide.agent.ports

/**
 * Порты движка к репозиторию (T-1.18, T-1.19): ветка задачи и снапшоты.
 *
 * Оба нужны в начале прогона и оба — про репозиторий, а не про состояние прогона,
 * поэтому приходят вместе: у движка это «что нужно от git», у каждой операции — свой
 * узкий порт. Отдельный тип нужен ещё и потому, что конструктор движка, перечисляющий
 * источники поимённо, перешагнул бы порог `LongParameterList`, а правило включено
 * и ослаблять его нельзя.
 *
 * Реализации лежат в `host-core` (О-1): рантайм агента о git не знает.
 */
class RepositoryPorts(
    /** Ветка задачи: поставить прогон в неё и запомнить базовую (T-1.18). */
    val branches: TaskBranches,

    /** Снапшоты: точка отката перед работой агента (T-1.19). */
    val snapshots: Snapshots,
)
