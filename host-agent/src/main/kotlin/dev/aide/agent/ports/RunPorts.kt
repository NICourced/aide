package dev.aide.agent.ports

/**
 * Порты движка к состоянию прогона (T-1.1, T-1.7): прогоны, задачи и рассылка событий.
 *
 * Три порта приходят вместе, потому что вместе они и нужны: очередь берёт задачи,
 * запись состояния — прогоны, задачи и рассылку, а по отдельности движок не пользуется
 * ни одним из них. Отдельный тип нужен ещё и потому, что их парами передают в оба
 * внутренних помощника движка — очередь и запись состояния, — и конструктор движка,
 * перечисляющий их поимённо, рос бы с каждым новым помощником.
 *
 * Реализации лежат в `host-core` (О-1): рантайм агента о базе не знает, он знает
 * только эти интерфейсы.
 */
class RunPorts(
    /** Прогоны: чтение и сохранение состояния, стоимость, время. */
    val runs: RunRepository,

    /** Задачи: очередь, статусы, причина отказа. */
    val tasks: TaskRepository,

    /** Рассылка смены состояния клиентам; событие идёт после записи (О-8). */
    val events: AgentEventSink,
)
