package dev.aide.agent.ports

import dev.aide.agent.RunInterruptReason

/**
 * Как движку досталась ветка задачи (T-1.18).
 *
 * Результат, а не «ветка или исключение»: «ветка уже была» и «ветку получить нельзя» —
 * обычные состояния репозитория (его правит человек), а не сбой хоста. Код отказа лежит
 * в [Refused.reason] — из словаря [RunInterruptReason]: понятную строку строит UI (NFR-13).
 */
sealed interface TaskBranch {

    /** Ветки не было: создана сейчас от [base] — её и надо запомнить как базовую. */
    data class Created(val base: String) : TaskBranch

    /** Ветка уже была: прогон продолжает её, история не тронута, базовая не переписывается. */
    data object Existing : TaskBranch

    /** Ветку задачи получить нельзя; [reason] — код причины отказа прогона. */
    data class Refused(val reason: String) : TaskBranch
}

/**
 * Единственное, что движку нужно от git (T-1.18, О-1).
 *
 * Рантайм агента о git не знает: ветками и репозиторием владеет хост, а движок получает
 * узкий порт — «обеспечь прогону его ветку». Шире он и не нужен: коммиты шагов (T-1.11)
 * и снапшоты (T-1.19) приносят свои порты.
 *
 * Реализация живёт в `host-core` рядом с `OpenWorkspaces`: переключить репозиторий —
 * значит знать, какой воркспейс открыт, а это знание хостовое.
 */
fun interface TaskBranches {

    /**
     * Ставит репозиторий в [branch] и говорит, откуда взялась ветка.
     *
     * Идемпотентно: ветки нет — создаётся от текущего HEAD; ветка есть — прогон
     * продолжает её, ref и история не переписываются. Отказ вместо исключения —
     * в [TaskBranch.Refused], потому что «репозиторий без коммитов» или «HEAD отсоединён»
     * это состояние репозитория, а не сбой движка.
     */
    suspend fun ensure(branch: String): TaskBranch
}
