package dev.aide.client.state

/**
 * Состояние экрана (§ 6.1).
 *
 * Один тип вместо набора флагов: нельзя одновременно оказаться в «загрузке»
 * и в «ошибке», а компилятор требует обработать все случаи в `when`.
 */
sealed interface ScreenState<out T> {

    /** Данных ещё нет и запрос не начат. */
    data object Empty : ScreenState<Nothing>

    /** Репозиторий не выбран: показывать нечего, пользователю нужно указать путь в настройках. */
    data object NoRepository : ScreenState<Nothing>

    /** Идёт загрузка; UI показывает скелетон структуры, а не пустой экран. */
    data object Loading : ScreenState<Nothing>

    /** Данные получены. */
    data class Loaded<T>(val data: T) : ScreenState<T>

    /**
     * Запрос завершился ошибкой.
     *
     * [arguments] — параметры текста, интерпретируемые по [kind]: пути, версии. Сам текст
     * строит UI из ресурсов (NFR-13); исключение — [ErrorKind.OTHER], где параметром служит
     * уже готовый текст хоста, который классифицировать нельзя.
     */
    data class Failed(
        /** Вид ошибки — от него зависит текст и действие. */
        val kind: ErrorKind,
        /** Параметры для текста ошибки; порядок задаётся видом [kind]. */
        val arguments: List<String> = emptyList(),
        /** Техническая деталь; показывается по запросу. */
        val technical: String? = null,
    ) : ScreenState<Nothing>

    /** Связь с хостом потеряна; показываются данные из кэша с явной пометкой (§ 3.5). */
    data class Offline<T>(val cached: T) : ScreenState<T>

    /** Доступ к объекту закрыт (§ 10.1). */
    data class NoPermission(
        /** К чему нет доступа. */
        val path: String,
        /** Почему отказано. */
        val reason: String,
    ) : ScreenState<Nothing>

    /** Виды ошибок, различаемые интерфейсом. */
    enum class ErrorKind {
        /** Путь не существует. */
        PATH_MISSING,

        /** Каталог есть, но это не git-репозиторий. */
        NOT_A_REPOSITORY,

        /** Воркспейс был открыт, но на хосте уже закрыт. */
        WORKSPACE_CLOSED,

        /** Версии протокола несовместимы. */
        INCOMPATIBLE,

        /**
         * Хост отверг конфигурацию моделей (T-1.56).
         *
         * Отдельный вид, а не [OTHER]: у этой ошибки нет текста от хоста — едет только код,
         * и строку строит UI из ресурсов. Подробности показывает раздел «Модель», где
         * настройку и правят.
         */
        CONFIG_REJECTED,

        /** Прочая ошибка: текст хоста, классифицировать нельзя. */
        OTHER,
    }
}
